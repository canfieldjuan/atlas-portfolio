export async function generateDeflectionDemoExample(options = {}) {
  const reportSourcePath = options.demoReportSourcePath ?? await resolveDefaultSourcePath(
    defaultDemoReportSourceCandidates,
    deflectionReportExampleFilename,
    '--demo-report-source',
  );
  const snapshotSourcePath = options.demoSnapshotSourcePath ?? await resolveDefaultSourcePath(
    defaultDemoSnapshotSourceCandidates,
    deflectionSnapshotExampleFilename,
    '--demo-snapshot-source',
  );
  const outputPath = options.demoExampleOutputPath ?? defaultDemoExampleOutputPath;
  const rendered = renderDeflectionDemoExample({
    reportExampleText: await readFile(reportSourcePath, 'utf8'),
    snapshotExampleText: await readFile(snapshotSourcePath, 'utf8'),
  });

  await writeOrCheckGeneratedContract({
    check: options.check,
    outputPath,
    rendered,
    sourcePath: `${reportSourcePath} + ${snapshotSourcePath}`,
    staleCommand: 'npm --prefix web run generate:deflection-contracts',
  });
}

export async function generateDeflectionContracts(options = {}) {
  if (options.print) {
    await generateDeflectionSnapshotContract(options);
    return;
  }
  await generateDeflectionSnapshotContract(options);
  await generateDeflectionReportModelContract(options);
  await generateDeflectionDemoExample(options);
}

export async function main(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  await generateDeflectionContracts(options);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((error) => {
    console.error(error.stack || error.message || error);
    process.exitCode = 1;
  });
}
