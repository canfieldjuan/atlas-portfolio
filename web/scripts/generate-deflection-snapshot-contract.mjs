import { access, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const webRoot = dirname(scriptDir);
const repoRoot = dirname(webRoot);
const defaultOutputPath = resolve(webRoot, 'src/lib/deflection-snapshot-contract.ts');
const defaultSourceCandidates = [
  resolve(repoRoot, '../Atlas/portfolio-ui/src/types/deflectionSnapshot.ts'),
  resolve(repoRoot, '../ATLAS/portfolio-ui/src/types/deflectionSnapshot.ts'),
];

const REQUIRED_SOURCE_SNIPPETS = [
  'Generated by scripts/generate_deflection_frontend_contract_types.py',
  'DEFLECTION_SNAPSHOT_TOP_LEVEL_FIELDS',
  'DEFLECTION_RESULT_PAGE_SNAPSHOT_FIELDS',
  'support_ticket_resolution_evidence_present',
  'support_ticket_resolution_evidence_count',
  'non_repeat_ticket_count',
  'top_blind_spots: DeflectionSnapshotTopBlindSpot[];',
];

const TYPE_NAME_REPLACEMENTS = [
  ['DeflectionSnapshotTopQuestion', 'DeflectionSnapshotQuestion'],
  ['DeflectionSnapshotTopBlindSpot', 'DeflectionSnapshotBlindSpot'],
  ['DeflectionSnapshotTeaserFullAnswer', 'DeflectionSnapshotFullAnswer'],
  ['DeflectionSnapshotTeaserPreview', 'DeflectionSnapshotAnswerPreview'],
];

export function renderDeflectionSnapshotContract(sourceText) {
  validateSourceContract(sourceText);
  const sourceBody = sourceText.replace(/^\/\*[\s\S]*?\*\/\s*/, '').trim();
  const mappedBody = TYPE_NAME_REPLACEMENTS.reduce(
    (body, [from, to]) => body.replaceAll(from, to),
    sourceBody,
  );

  return [
    '/*',
    ' * Generated by web/scripts/generate-deflection-snapshot-contract.mjs.',
    ' * Source: ATLAS portfolio-ui/src/types/deflectionSnapshot.ts,',
    ' * generated from the backend deflection report contract.',
    ' * Do not edit by hand; run npm --prefix web run generate:deflection-snapshot-contract.',
    ' */',
    '',
    mappedBody,
    '',
    'export type DeflectionSnapshotSourceWindow = {',
    '  source_date_start: string;',
    '  source_date_end: string;',
    '  source_window_days: number;',
    '};',
    '',
  ].join('\n');
}

function validateSourceContract(sourceText) {
  const missing = REQUIRED_SOURCE_SNIPPETS.filter((snippet) => !sourceText.includes(snippet));
  if (missing.length > 0) {
    throw new Error(`ATLAS Snapshot contract source is missing required markers: ${missing.join(', ')}`);
  }
}

async function resolveDefaultSourcePath() {
  for (const candidate of defaultSourceCandidates) {
    try {
      await access(candidate);
      return candidate;
    } catch {
      // Try the next common local checkout spelling.
    }
  }
  throw new Error(
    [
      'Could not find the ATLAS generated Snapshot contract source.',
      'Pass --source <path-to-ATLAS/portfolio-ui/src/types/deflectionSnapshot.ts>.',
    ].join(' '),
  );
}

function parseArgs(argv) {
  const options = {
    check: false,
    outputPath: defaultOutputPath,
    print: false,
    sourcePath: null,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--check') {
      options.check = true;
      continue;
    }
    if (arg === '--print') {
      options.print = true;
      continue;
    }
    if (arg === '--source') {
      options.sourcePath = resolve(requireValue(argv, index, arg));
      index += 1;
      continue;
    }
    if (arg === '--output') {
      options.outputPath = resolve(requireValue(argv, index, arg));
      index += 1;
      continue;
    }
    throw new Error(`Unknown argument: ${arg}`);
  }

  return options;
}

function requireValue(argv, index, flag) {
  const value = argv[index + 1];
  if (!value || value.startsWith('--')) {
    throw new Error(`${flag} requires a path value`);
  }
  return value;
}

function firstDifference(expected, actual) {
  const expectedLines = expected.split('\n');
  const actualLines = actual.split('\n');
  const max = Math.max(expectedLines.length, actualLines.length);
  for (let index = 0; index < max; index += 1) {
    if (expectedLines[index] !== actualLines[index]) {
      return {
        actual: actualLines[index] ?? '<missing>',
        expected: expectedLines[index] ?? '<missing>',
        line: index + 1,
      };
    }
  }
  return null;
}

export async function generateDeflectionSnapshotContract(options = {}) {
  const sourcePath = options.sourcePath ?? await resolveDefaultSourcePath();
  const outputPath = options.outputPath ?? defaultOutputPath;
  const sourceText = await readFile(sourcePath, 'utf8');
  const rendered = renderDeflectionSnapshotContract(sourceText);

  if (options.print) {
    process.stdout.write(rendered);
  }

  if (options.check) {
    const current = await readFile(outputPath, 'utf8');
    if (current !== rendered) {
      const diff = firstDifference(rendered, current);
      throw new Error(
        [
          `${outputPath} is out of date with ${sourcePath}.`,
          diff ? `First difference at line ${diff.line}: expected ${JSON.stringify(diff.expected)}, found ${JSON.stringify(diff.actual)}.` : '',
          'Run npm --prefix web run generate:deflection-snapshot-contract.',
        ].filter(Boolean).join(' '),
      );
    }
    console.log(`${outputPath} matches ${sourcePath}.`);
    return;
  }

  if (!options.print) {
    await writeFile(outputPath, rendered, 'utf8');
    console.log(`Wrote ${outputPath} from ${sourcePath}.`);
  }
}

export async function main(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  await generateDeflectionSnapshotContract(options);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((error) => {
    console.error(error.stack || error.message || error);
    process.exitCode = 1;
  });
}
